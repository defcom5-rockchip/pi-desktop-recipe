#!/usr/bin/env python3
# Plaid Pi wordmark: the tartan pi logo (pi-desktop.svg) followed by "Plaid Pi" in DejaVu Sans Bold, as filled
# paths (no fonts at render time), in a 400 x 64 viewBox like the distro wordmarks GDM shows under the login box.
# Two colourways: -dark (cream text, for dark backgrounds such as the GDM greeter) and the plain one (charcoal text).
# Artwork (c) 2026 defcom5-rockchip, CC BY-SA 4.0, like everything in this directory.
#   python3 make-wordmark.py            -> writes plaid-pi-logo-text.svg and plaid-pi-logo-text-dark.svg here
import importlib.util
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('ml', os.path.join(HERE, 'make-logo.py'))
ml = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ml)

FONT = '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf'
TEXT = 'Plaid Pi'
W, H = 400, 64
TEXT_X = 80            # text starts 16 units after the 64-unit logo
CAP_H = 36             # cap height of the text in viewBox units
COLOURS = {'': '#1C1B1A', '-dark': '#F3E2B8'}


def font_tables(path):
    data = open(path, 'rb').read()
    n = struct.unpack('>H', data[4:6])[0]
    t = {}
    for i in range(n):
        tag, _cs, off, ln = struct.unpack('>4sIII', data[12 + 16 * i:28 + 16 * i])
        t[tag.decode('latin1')] = data[off:off + ln]
    return t


def advances(path):
    """glyph advance widths via cmap format 4 + hhea/hmtx, keyed by character."""
    t = font_tables(path)
    cmap, hhea, hmtx, os2 = t['cmap'], t['hhea'], t['hmtx'], t.get('OS/2')
    n_hm = struct.unpack('>H', hhea[34:36])[0]
    widths = [struct.unpack('>H', hmtx[4 * i:4 * i + 2])[0] for i in range(n_hm)]

    def gid(cp):
        for i in range(struct.unpack('>H', cmap[2:4])[0]):
            _p, _e, off = struct.unpack('>HHI', cmap[4 + 8 * i:12 + 8 * i])
            if struct.unpack('>H', cmap[off:off + 2])[0] != 4:
                continue
            seg2 = struct.unpack('>H', cmap[off + 6:off + 8])[0]
            seg = seg2 // 2
            ends = struct.unpack(f'>{seg}H', cmap[off + 14:off + 14 + seg2])
            starts = struct.unpack(f'>{seg}H', cmap[off + 16 + seg2:off + 16 + 2 * seg2])
            deltas = struct.unpack(f'>{seg}h', cmap[off + 16 + 2 * seg2:off + 16 + 3 * seg2])
            rb = off + 16 + 3 * seg2
            ros = struct.unpack(f'>{seg}H', cmap[rb:rb + seg2])
            for k in range(seg):
                if starts[k] <= cp <= ends[k]:
                    if ros[k] == 0:
                        return (cp + deltas[k]) & 0xFFFF
                    a = rb + 2 * k + ros[k] + 2 * (cp - starts[k])
                    g = struct.unpack('>H', cmap[a:a + 2])[0]
                    return (g + deltas[k]) & 0xFFFF if g else 0
        return 0

    cap = struct.unpack('>h', os2[88:90])[0] if os2 and len(os2) >= 90 else 1493   # sCapHeight (OS/2 v2+)
    return (lambda ch: widths[min(gid(ord(ch)), n_hm - 1)]), cap


def text_path():
    adv, cap = advances(FONT)
    s = CAP_H / cap
    base = (H + CAP_H) / 2                     # vertically centre the caps on the 64-unit line
    x = 0.0
    parts = []
    for ch in TEXT:
        if ch != ' ':
            (contours, _upem) = ml.glyph_contours_builtin(FONT, ord(ch))
            ox = x

            def tf(px, py, ox=ox):
                return TEXT_X + (ox + px) * s, base - py * s
            parts.append(ml.contours_to_path(contours, tf))
        x += adv(ch)
    return ''.join(parts), TEXT_X + x * s


def logo_group():
    svg = open(os.path.join(HERE, 'pi-desktop.svg')).read()
    inner = re.search(r'<svg[^>]*>(.*)</svg>', svg, re.S).group(1)
    # keep internal ids unique per file; the logo is already a 64 x 64 viewBox, drawn at the origin
    return inner


def build(suffix, colour):
    d, right = text_path()
    if right > W - 2:
        raise SystemExit(f'text too wide: ends at {right:.1f} of {W}')
    head = ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<!-- Plaid Pi wordmark (tartan pi logo + "Plaid Pi" in DejaVu Sans Bold as paths). '
            'Artwork (c) 2026 defcom5-rockchip, CC BY-SA 4.0. Generated by make-wordmark.py. -->\n')
    dx = (W - right) / 2                       # centre logo + text in the frame (GDM centres the image)
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" '
           f'width="{W}" height="{H}" viewBox="0 0 {W} {H}">\n'
           f'<g transform="translate({ml.f(dx)} 0)">\n<g>{logo_group()}</g>\n'
           f'<path fill="{colour}" d="{d}"/>\n</g>\n</svg>\n')
    out = os.path.join(sys.argv[1] if len(sys.argv) > 1 else HERE, f'plaid-pi-logo-text{suffix}.svg')
    open(out, 'w').write(head + svg)
    print(f'wrote {out} (text ends at x={right:.1f})')


if __name__ == '__main__':
    for suf, col in COLOURS.items():
        build(suf, col)
